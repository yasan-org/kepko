package glass.yasan.kepko.buildlogic.icons

import com.squareup.kotlinpoet.AnnotationSpec
import com.squareup.kotlinpoet.ClassName
import com.squareup.kotlinpoet.FileSpec
import com.squareup.kotlinpoet.FunSpec
import com.squareup.kotlinpoet.KModifier
import com.squareup.kotlinpoet.LambdaTypeName
import com.squareup.kotlinpoet.MemberName
import com.squareup.kotlinpoet.ParameterSpec
import com.squareup.kotlinpoet.PropertySpec
import com.squareup.kotlinpoet.STRING
import com.squareup.kotlinpoet.TypeSpec

/**
 * Generates the `Icons` object, with one `Painter` property per icon, and the `NamedIcon`
 * enum, which exposes the same icons under stable string ids for serialization.
 */
internal object IconsSourceGenerator {

    private const val FILE_COMMENT = "Generated by the syncIcons task from icons.yaml. Do not edit by hand."

    private val composable = ClassName("androidx.compose.runtime", "Composable")
    private val painter = ClassName("androidx.compose.ui.graphics.painter", "Painter")
    private val painterResource = MemberName("org.jetbrains.compose.resources", "painterResource")

    fun generate(packageName: String, iconsName: String, namedIconName: String, icons: List<Icon>): List<FileSpec> {
        val sorted = icons.sortedBy { it.propertyName.lowercase() }
        return listOf(
            icons(packageName, iconsName, sorted),
            namedIcon(packageName, iconsName, namedIconName, sorted),
        )
    }

    private fun icons(packageName: String, iconsName: String, icons: List<Icon>): FileSpec {
        val res = ClassName(packageName, "Res")
        val type = TypeSpec.objectBuilder(iconsName)
            .addModifiers(KModifier.PUBLIC)
            .addProperties(
                icons.map { icon ->
                    PropertySpec.builder(icon.propertyName, painter, KModifier.PUBLIC)
                        .getter(
                            FunSpec.getterBuilder()
                                .addAnnotation(composable)
                                .addStatement("return %M(%T.drawable.%L)", painterResource, res, icon.resourceName)
                                .build(),
                        )
                        .build()
                },
            )
            .build()
        return file(packageName, iconsName, type)
    }

    private fun namedIcon(packageName: String, iconsName: String, namedIconName: String, icons: List<Icon>): FileSpec {
        val iconsClass = ClassName(packageName, iconsName)
        val namedIconClass = ClassName(packageName, namedIconName)
        val painterLambda = LambdaTypeName.get(returnType = painter)
            .copy(annotations = listOf(AnnotationSpec.builder(composable).build()))

        val type = TypeSpec.enumBuilder(namedIconName)
            .addModifiers(KModifier.PUBLIC)
            .primaryConstructor(
                FunSpec.constructorBuilder()
                    .addParameter(ParameterSpec("id", STRING))
                    .addParameter(ParameterSpec("painter", painterLambda))
                    .build(),
            )
            .addProperty(PropertySpec.builder("id", STRING, KModifier.PUBLIC).initializer("id").build())
            .addProperty(PropertySpec.builder("painter", painterLambda, KModifier.PUBLIC).initializer("painter").build())
            .apply {
                icons.forEach { icon ->
                    addEnumConstant(
                        icon.constantName,
                        TypeSpec.anonymousClassBuilder()
                            .addSuperclassConstructorParameter("id = %S", icon.name)
                            .addSuperclassConstructorParameter("painter = { %T.%N }", iconsClass, icon.propertyName)
                            .build(),
                    )
                }
            }
            .addType(
                TypeSpec.companionObjectBuilder()
                    .addModifiers(KModifier.PUBLIC)
                    .addFunction(
                        FunSpec.builder("fromIdOrNull")
                            .addModifiers(KModifier.PUBLIC)
                            .addParameter("id", STRING)
                            .returns(namedIconClass.copy(nullable = true))
                            .addStatement("return entries.firstOrNull { it.id == id }")
                            .build(),
                    )
                    .build(),
            )
            .build()
        return file(packageName, namedIconName, type)
    }

    private fun file(packageName: String, name: String, type: TypeSpec): FileSpec =
        FileSpec.builder(packageName, name)
            .addFileComment(FILE_COMMENT)
            .indent("    ")
            .addType(type)
            .build()
}
